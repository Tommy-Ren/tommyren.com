function createFocusTarget({ id, label, position, panelPosition, cameraPosition, lookAt }) {
  return {
    id,
    label,
    position,
    panelPosition: panelPosition || position,
    cameraPosition: cameraPosition || position,
    lookAt: lookAt || panelPosition || position,
  }
}

